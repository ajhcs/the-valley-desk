function withLockedBase<T extends { id: string; source: { origin: string; url?: string } }>(
  item: T,
): T & { impactSentence?: string; geo?: string; citations?: { name: string; url: string }[] } {
  const url = item.source.url ?? SOURCE_URL[item.id]
  const impactSentence = IMPACT[item.id]
  const geo = GEO[item.id]
  return {
    ...item,
    impactSentence,
    geo,
    source: url ? { ...item.source, url } : item.source,
    citations: url ? [{ name: item.source.origin, url }] : undefined,
  }
}

