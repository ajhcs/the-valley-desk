import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const items = JSON.parse(readFileSync(join(root, "fixtures/catalog.json"), "utf8"));

const SITE = "https://thevalleydesk.org";
const NEWS_PERMALINK_KINDS = new Set(["news", "policy", "ai", "interview"]);

function canonicalPath(item) {
  if (item.kind === "event") return "/events/" + item.slug;
  if (NEWS_PERMALINK_KINDS.has(item.kind)) return "/news/" + item.slug;
  if (item.kind === "voice") return "/voices/" + item.slug;
  if (item.kind === "briefing") return "/briefing/" + item.slug;
  return "/" + item.kind + "/" + item.slug;
}

function canonicalUrl(item) {
  return SITE + canonicalPath(item);
}

function hasCite(item) {
  const cited = Array.isArray(item.citations) && item.citations.some((c) => c && c.url);
  return Boolean((item.source && item.source.url) || cited);
}

const published = items.filter((item) => item.status === "published" && hasCite(item));
const generatedAt = published
  .map((item) => item.updatedAt || item.publishedAt)
  .filter(Boolean)
  .sort()
  .at(-1) || "1970-01-01T00:00:00.000Z";

const doc = {
  product: "the-valley-desk",
  version: "1",
  generatedAt,
  items: published,
};

function esc(s = "") {
  return String(s)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

// Reed lock: RSS <link> and <guid> are our canonical permalink only.
// source.url stays on the JSON item as citation. Never the RSS link.
const rssItems = published
  .map((item) => {
    const link = canonicalUrl(item);
    const desc = item.impactSentence
      || (item.kind === "event" && item.whyAttend && !/best-effort scrape|ingested from/i.test(item.whyAttend) ? item.whyAttend : item.healthSystemRelevance)
      || item.dek
      || item.body
      || item.title;
    const pub = item.publishedAt || item.updatedAt;
    const pubDate = new Date(pub);
    const generatedDate = new Date(generatedAt);
    const safePubDate = Number.isNaN(pubDate.valueOf()) || pubDate > generatedDate
      ? generatedDate
      : pubDate;
    return `    <item>
      <title>${esc(item.title)}</title>
      <link>${esc(link)}</link>
      <guid isPermaLink="true">${esc(link)}</guid>
      <description>${esc(desc)}</description>
      <pubDate>${safePubDate.toUTCString()}</pubDate>
    </item>`;
  })
  .join("\n");

const rss = `<?xml version="1.0" encoding="UTF-8"?>
<rss version="2.0">
  <channel>
    <title>The Valley Desk</title>
    <link>${SITE}/</link>
    <description>Local health-tech news for people and agents</description>
    <lastBuildDate>${new Date(generatedAt).toUTCString()}</lastBuildDate>
${rssItems}
  </channel>
</rss>
`;

const sitemapPaths = [
  "/",
  "/news",
  "/events",
  "/voices",
  ...published.map(canonicalPath),
  "/feed.json",
  "/feed.xml",
];
const seen = new Set();
const loc = [...sitemapPaths].filter((p) => (seen.has(p) ? false : seen.add(p)));
const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${loc.map((path) => `  <url><loc>${SITE}${path === "/" ? "/" : path}</loc></url>`).join("\n")}
</urlset>
`;

const publishedNewsSlugs = published
  .filter((item) => NEWS_PERMALINK_KINDS.has(item.kind))
  .map((item) => item.slug)
  .sort();
const publishedEventSlugs = published
  .filter((item) => item.kind === "event")
  .map((item) => item.slug)
  .sort();
const publishedVoiceSlugs = published
  .filter((item) => item.kind === "voice")
  .map((item) => item.slug)
  .sort();
const publishedBriefingSlugs = published
  .filter((item) => item.kind === "briefing")
  .map((item) => item.slug)
  .sort();
const publishedHead = Object.fromEntries(
  published.map((item) => [
    item.slug,
    {
      id: item.id,
      kind: item.kind,
      title: item.title,
      description: (item.impactSentence && String(item.impactSentence).trim()) || item.title,
    },
  ]),
);
const publishedSlugRedirects = {};
for (const item of published) {
  for (const old of item.previousSlugs ?? []) {
    if (!old || old === item.slug || publishedHead[old]) continue;
    publishedSlugRedirects[old] = { kind: item.kind, slug: item.slug };
  }
}
const publishedRoutes = `/** Generated by scripts/build-feed.mjs. Published permalink slugs only. */
export const publishedNewsSlugs = ${JSON.stringify(publishedNewsSlugs, null, 2)};
export const publishedEventSlugs = ${JSON.stringify(publishedEventSlugs, null, 2)};
export const publishedVoiceSlugs = ${JSON.stringify(publishedVoiceSlugs, null, 2)};
export const publishedBriefingSlugs = ${JSON.stringify(publishedBriefingSlugs, null, 2)};
export const publishedSlugRedirects = ${JSON.stringify(publishedSlugRedirects, null, 2)};
export const publishedHead = ${JSON.stringify(publishedHead, null, 2)};
`;

mkdirSync(join(root, "public"), { recursive: true });
mkdirSync(join(root, "src/content"), { recursive: true });
writeFileSync(join(root, "public/feed.json"), JSON.stringify(doc, null, 2) + "\n");
writeFileSync(join(root, "public/feed.xml"), rss);
writeFileSync(join(root, "public/sitemap.xml"), sitemap);
writeFileSync(join(root, "worker-published.js"), publishedRoutes);
writeFileSync(join(root, "src/content/published-catalog.json"), JSON.stringify(published, null, 2) + "\n");
console.log(
  "wrote public/feed.json (" +
    published.length +
    "), public/feed.xml, public/sitemap.xml, worker-published.js, src/content/published-catalog.json",
);
